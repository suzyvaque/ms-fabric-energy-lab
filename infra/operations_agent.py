"""Step 12: operations agents (Real-Time Intelligence, preview) vs Activator. Idempotent. Dev only.

  py infra/operations_agent.py create --phase 0   # opa_obs_smoke: one table, one numeric "is above" rule (isolates
                                                  # service/tenant problems from instruction problems)
  py infra/operations_agent.py create --phase 1   # opa_obs_fleet: obs_fleet only; battery overheating + critical fault
  py infra/operations_agent.py create --phase 2   # opa_obs_jobs: obs_monitor job_events; the Fabric item action
                                                  # (run pl_obs_remediation after approval in Teams) is added in the portal
  py infra/operations_agent.py create --phase 3   # opa_obs_fleet gets ont_contoso as a 2nd source + priority rule
  py infra/operations_agent.py start|stop [--name opa_obs_fleet]
  py infra/operations_agent.py status             # definition, playbook (generated by the service?), run state
Playbooks can only be generated in the portal ("Generate playbook"); start the agent there or with `start` afterwards.

Runs in the isolated obs lab (ce-obs-ops on the obs capacity, infra/obs_lab.py); sources are the obs_fleet / obs_monitor
KQL databases fed by their own simulator, so injections never reach the shared dev stream (plan review #1).
Not in Git (like Activators, D-018): the definition carries the recipient UPN / sponsor. Script-managed.
"""
