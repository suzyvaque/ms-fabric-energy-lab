"""Step 12: operations agents (Real-Time Intelligence, preview) vs Activator. Idempotent. Dev only.

  py infra/operations_agent.py create --phase 1   # opa_fleet_ops: eh_fleet only; same two conditions as the Activators
  py infra/operations_agent.py create --phase 2   # opa_job_remediation: cap_monitoring job events + FabricJobAction
                                                  # (re-run pl_finance_daily after approval in Teams)
  py infra/operations_agent.py create --phase 3   # opa_fleet_ops gets ont_contoso as a 2nd source + cross-domain rule
  py infra/operations_agent.py start|stop [--name opa_fleet_ops]
  py infra/operations_agent.py status             # definition, playbook (generated by the service?), run state
  py infra/operations_agent.py logs               # what the agents and Activators emitted (workspace monitoring tables)

Runs in the isolated obs lab (ce-obs-ops on the obs capacity, infra/obs_lab.py); sources are the obs_fleet / obs_monitor
KQL databases fed by their own simulator, so injections never reach the shared dev stream (plan review #1).
Not in Git (like Activators, D-018): the definition carries the recipient UPN / sponsor. Script-managed.
"""
from __future__ import annotations

import argparse
import base64
import json
import uuid

from common import env, load_env, log
from fabric_rest import FABRIC, _request, b64, fabric, find_item, upsert_item
from finance_lakehouse import ws
from rti_lab import platform

FLEET = "opa_obs_fleet"
JOBS = "opa_obs_jobs"


def gid(name: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"contoso-energy-lab/opa/{name}"))


FLEET_INSTRUCTIONS = """You monitor the Contoso Energy residential solar + battery fleet (synthetic data) in the obs_fleet database.
Goal: operators learn about device faults and offline sites within minutes, with enough context to act.
Data: silver_alerts (alert_id, event_type raised/cleared, severity, alert_code, device_id, site_id, event_time, ingest_time);
silver_telemetry (device readings: device_id, site_id, device_type, status, ingest_time); dim_site (site_id, region).
Rules:
1. Device fault: when an alert with event_type 'raised' and severity High, Critical or Medium arrives, notify me once per
   alert_id with site_id, region, device_id, alert_code, severity and how long ago it was raised.
2. Site offline: when a site's gateway (device_type 'gateway') has sent no reading for 20 minutes, notify me once per outage
   with site_id, region and minutes offline.
Do not notify for Low severity or for alerts that were already cleared. Group simultaneous alerts at the same site."""

FLEET_ONTOLOGY_RULE = """
3. Business priority (uses the ont_contoso ontology): when rule 1 or 2 fires for a Site whose Contract status is Delinquent or
   Default, or whose Battery has state_of_health_pct below 80 before warranty_end, mark the notification PRIORITY and include
   the contract status and battery health. Never include customer names, emails or phone numbers."""

JOB_INSTRUCTIONS = """You watch Fabric job events in the obs_monitor database, table job_events (event_time, event_type,
item_name, item_kind, job_status, job_instance_id, duration_ms).
Goal: a failed daily job is noticed and remediated quickly, with a human approving the remediation.
Rule: when an event with event_type 'ItemJobFailed' arrives for item_name 'pl_obs_daily', notify me with the time, duration
and job_instance_id, and recommend the action 'Run remediation pipeline' with reason = the job_instance_id.
Do not recommend it if pl_obs_daily already succeeded after the failure (a later 'ItemJobSucceeded' for pl_obs_daily)."""


def kusto_source(db: str) -> dict:
    from obs_lab import wid
    w = wid("ops")
    return {"id": find_item(w, "KQLDatabase", db)["id"], "type": "KustoDatabase", "workspaceId": w}


def definition(phase: int, name: str) -> dict:
    recipient = {"kind": "Recipient", "recipient": env("ALERT_EMAIL", required=False) or env("ADMIN_UPN")}
    if name == FLEET:
        sources = {"fleet": kusto_source("obs_fleet")}
        instructions = FLEET_INSTRUCTIONS
        if phase >= 3:
            aw = ws("asset", "dev")
            sources["contoso"] = {"id": find_item(aw, "Ontology", "ont_contoso")["id"], "type": "Ontology", "workspaceId": aw}
            instructions += FLEET_ONTOLOGY_RULE
        actions = {}
    else:
        from obs_lab import wid
        fw = wid("ops")
        pl = find_item(fw, "DataPipeline", "pl_obs_remediation")
        sources = {"jobs": kusto_source("obs_monitor")}
        instructions = JOB_INSTRUCTIONS
        actions = {"rerunFinance": {"id": gid("rerun"), "kind": "FabricJobAction", "displayName": "Re-run finance pipeline",
                                    "description": "Runs pl_finance_daily (failure_mode none) after approval",
                                    "connection": {"jobArtifactId": pl["id"], "jobWorkspaceId": fw, "itemType": "DataPipeline",
                                                   "jobType": "Pipeline"},
                                    "parameters": [{"name": "reason", "description": "Why the remediation runs (failed job id)"}]}}
    return {"configuration": {"instructions": instructions, "dataSources": sources, "actions": actions,
                              "messageDestination": recipient},
            "playbook": {}, "shouldRun": False}


def home(name: str) -> str:
    from obs_lab import wid
    return wid("ops")


def create(phase: int) -> None:
    """Item first (empty), then configuration. The playbook (rules) can only be generated in the portal
    ("Generate playbook"); the API rejects any authored playbook with "No rule definitions available in the playbook"
    and refuses shouldRun=true without one. An existing generated playbook is preserved on update."""
    names = [FLEET] if phase in (1, 3) else [JOBS]
    for name in names:
        w = home(name)
        item = find_item(w, "OperationsAgent", name) or upsert_item(w, "OperationsAgent", name, None,
                                                                   f"Step 12 phase {phase}: operations agent")
        d = definition(phase, name)
        cur = get_def(w, item["id"])
        if cur.get("playbook"):
            d["playbook"], d["shouldRun"] = cur["playbook"], cur.get("shouldRun", False)
        else:
            d.pop("playbook")
        status, _, body = _request("post", f"{FABRIC}/v1/workspaces/{w}/items/{item['id']}/updateDefinition",
                                   {"definition": {"parts": [{"path": "Configurations.json", "payload": b64(d),
                                                              "payloadType": "InlineBase64"}]}}, FABRIC)
        if status not in (200, 202):
            raise SystemExit(f"{name}: {status} {json.dumps(body)[:400]}")
        log(f"{name}: phase {phase} configuration applied ({len(d['configuration']['dataSources'])} source(s), "
            f"{len(d['configuration']['actions'])} action(s)); playbook {'kept' if 'playbook' in d else 'NOT generated yet (portal)'}")


def get_def(w: str, item_id: str) -> dict:
    parts = fabric("post", f"workspaces/{w}/items/{item_id}/getDefinition")["definition"]["parts"]
    return json.loads(base64.b64decode(next(p["payload"] for p in parts if p["path"] == "Configurations.json")))


def set_run(name: str, run: bool) -> None:
    w = home(name)
    item = find_item(w, "OperationsAgent", name)
    d = get_def(w, item["id"])
    d["shouldRun"] = run
    status, _, body = _request("post", f"{FABRIC}/v1/workspaces/{w}/items/{item['id']}/updateDefinition",
                               {"definition": {"parts": [{"path": "Configurations.json", "payload": b64(d),
                                                          "payloadType": "InlineBase64"}]}}, FABRIC)
    if status not in (200, 202):
        raise SystemExit(f"{name}: {status} {json.dumps(body)[:500]}")
    log(f"{name}: shouldRun={run}")


def status() -> None:
    for name in (FLEET, JOBS):
        w = home(name)
        item = find_item(w, "OperationsAgent", name)
        if not item:
            print(f"{name}: not created")
            continue
        d = get_def(w, item["id"])
        pb = d.get("playbook") or {}
        print(f"{name}: shouldRun={d.get('shouldRun')} sources={list(d['configuration']['dataSources'])} "
              f"actions={list(d['configuration']['actions'])} playbook keys={list(pb)[:8]} size={len(json.dumps(pb))}")
        if pb:
            print("  playbook:", json.dumps(pb)[:1500])


def main() -> None:
    import sys
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    p = argparse.ArgumentParser()
    p.add_argument("action", choices=["create", "start", "stop", "status"])
    p.add_argument("--phase", type=int, default=1)
    p.add_argument("--name", default=FLEET)
    a = p.parse_args()
    load_env()
    if a.action == "create":
        create(a.phase)
    elif a.action in ("start", "stop"):
        set_run(a.name, a.action == "start")
    else:
        status()


if __name__ == "__main__":
    main()
