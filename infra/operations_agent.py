# Smoke test: the docs' own pattern ("alert me when motor temperature gets too high"), one table, one numeric property.
SMOKE_INSTRUCTIONS = """Monitor each device in silver_telemetry, identified by device_id. Alert me when battery_temp_c is above 55."""


def kusto_source(db: str) -> dict:
    from obs_lab import wid
    w = wid("ops")
    return {"id": find_item(w, "KQLDatabase", db)["id"], "type": "KustoDatabase", "workspaceId": w}


def definition(phase: int, name: str) -> dict:
    recipient = {"kind": "Recipient", "recipient": env("ALERT_EMAIL", required=False) or env("ADMIN_UPN")}
    if name == SMOKE:
        return {"configuration": {"instructions": SMOKE_INSTRUCTIONS, "dataSources": {"fleet": kusto_source("obs_fleet")},
                                  "actions": {}, "messageDestination": recipient}, "playbook": {}, "shouldRun": False}
    if name == FLEET:
        sources = {"fleet": kusto_source("obs_fleet")}
        instructions = FLEET_INSTRUCTIONS
        if phase >= 3:
            aw = ws("asset", "dev")
            sources["contoso"] = {"id": find_item(aw, "Ontology", "ont_contoso")["id"], "type": "Ontology", "workspaceId": aw}
            instructions += FLEET_ONTOLOGY_RULE
        actions = {}
    else:
        sources = {"jobs": kusto_source("obs_monitor")}
        instructions = JOB_INSTRUCTIONS
        # FabricJobAction is rejected by updateDefinition (UnknownError); the action is added in the portal and preserved.
        actions = {}
    return {"configuration": {"instructions": instructions, "dataSources": sources, "actions": actions,
                              "messageDestination": recipient},
            "playbook": {}, "shouldRun": False}


def home(name: str) -> str:
    from obs_lab import wid
    return wid("ops")


def create(phase: int) -> None:
    """Item first (empty), then configuration. The playbook (rules) can only be generated in the portal
    ("Generate playbook"); the API rejects any authored playbook with "No rule definitions available in the playbook"
    and refuses shouldRun=true without one. An existing generated playbook is preserved on update."""
    names = {0: [SMOKE], 1: [FLEET], 2: [JOBS], 3: [FLEET]}[phase]
    for name in names:
        w = home(name)
        item = find_item(w, "OperationsAgent", name) or upsert_item(w, "OperationsAgent", name, None,
                                                                   f"Step 12 phase {phase}: operations agent")
        d = definition(phase, name)
        cur = get_def(w, item["id"])
        if cur.get("configuration", {}).get("actions") and not d["configuration"]["actions"]:
            d["configuration"]["actions"] = cur["configuration"]["actions"]  # keep actions added in the portal
        if cur.get("playbook"):
            d["playbook"], d["shouldRun"] = cur["playbook"], cur.get("shouldRun", False)
        else:
            d.pop("playbook")
        status, _, body = _request("post", f"{FABRIC}/v1/workspaces/{w}/items/{item['id']}/updateDefinition",
                                   {"definition": {"parts": [{"path": "Configurations.json", "payload": b64(d),
                                                              "payloadType": "InlineBase64"}]}}, FABRIC)
        if status not in (200, 202):
            raise SystemExit(f"{name}: {status} {json.dumps(body)[:400]}")
        log(f"{name}: phase {phase} configuration applied ({len(d['configuration']['dataSources'])} source(s), "
            f"{len(d['configuration']['actions'])} action(s)); playbook {'kept' if 'playbook' in d else 'NOT generated yet (portal)'}")


def get_def(w: str, item_id: str) -> dict:
    parts = fabric("post", f"workspaces/{w}/items/{item_id}/getDefinition")["definition"]["parts"]
    return json.loads(base64.b64decode(next(p["payload"] for p in parts if p["path"] == "Configurations.json")))


def set_run(name: str, run: bool) -> None:
    w = home(name)
    item = find_item(w, "OperationsAgent", name)
    d = get_def(w, item["id"])
    d["shouldRun"] = run
    status, _, body = _request("post", f"{FABRIC}/v1/workspaces/{w}/items/{item['id']}/updateDefinition",
                               {"definition": {"parts": [{"path": "Configurations.json", "payload": b64(d),
                                                          "payloadType": "InlineBase64"}]}}, FABRIC)
    if status not in (200, 202):
        raise SystemExit(f"{name}: {status} {json.dumps(body)[:500]}")
    log(f"{name}: shouldRun={run}")


def status() -> None:
    for name in (SMOKE, FLEET, JOBS):
        w = home(name)
        item = find_item(w, "OperationsAgent", name)
        if not item:
            print(f"{name}: not created")
            continue
        d = get_def(w, item["id"])
        pb = d.get("playbook") or {}
        print(f"{name}: shouldRun={d.get('shouldRun')} sources={list(d['configuration']['dataSources'])} "
              f"actions={list(d['configuration']['actions'])} playbook keys={list(pb)[:8]} size={len(json.dumps(pb))}")
        if pb:
            print("  playbook:", json.dumps(pb)[:1500])


def evidence(since: str, truth_dir: str) -> None:
    """Phase 1 timeline per injected site: anomaly start (ground truth), first telemetry above 55 C, raised alert, Activator
    probe firing (pipeline run in job_events), Activator notifications, and agent rule queries (workspace monitoring)."""
    import csv
    import glob
    from fabric_rest import kql
    from obs_lab import state
    s = state()
    q = s["query_uri"]
    fleet = s["obs_fleet"] if isinstance(s["obs_fleet"], str) else s["obs_fleet"]["id"]
    mon = s["obs_monitor"] if isinstance(s["obs_monitor"], str) else s["obs_monitor"]["id"]
    truth = [r for f in glob.glob(f"{truth_dir}/ground_truth/*.csv") for r in csv.DictReader(open(f, encoding="utf-8"))]
    sites = sorted({r["site_id"] for r in truth})
    print("ground truth:", [(r["site_id"], r.get("anomaly_type") or r.get("type"), r.get("start") or r.get("start_time"))
                            for r in truth])
    sl = ",".join(f"'{x}'" for x in sites)
    t = f"datetime({since})"
    hot = kql(q, fleet, f"silver_telemetry | where ingest_time > {t} and site_id in ({sl}) and battery_temp_c > 55 "
                        f"| summarize first_hot=min(ingest_time), last_hot=max(ingest_time), max_temp=max(battery_temp_c), "
                        f"n=count() by site_id")
    alerts = kql(q, fleet, f"silver_alerts | where ingest_time > {t} and site_id in ({sl}) and alert_code == 'BATT_OVERTEMP' "
                           f"| summarize raised=make_list_if(ingest_time, event_type == 'raised'), "
                           f"cleared=countif(event_type == 'cleared') by site_id")
    fired = kql(q, mon, f"job_events | where event_time > {t} and item_name == 'pl_obs_remediation' "
                        f"and event_type == 'ItemJobCreated' | project event_time, invoke_type | order by event_time asc")
    print("\ntelemetry > 55 C:", json.dumps(hot, indent=1))
    print("\nBATT_OVERTEMP alerts:", json.dumps(alerts, indent=1))
    print("\nActivator probe firings (pl_obs_remediation created):", json.dumps(fired, indent=1))
    from fabric_rest import fabric
    aud = s["workspaces"]["audit"]
    db = find_item(aud, "KQLDatabase", "ce-obs-ops_mon_obs_ops_Database")
    qu = fabric("get", f"workspaces/{aud}/kqlDatabases/{db['id']}")["properties"]["queryServiceUri"]
    agent = kql(qu, db["id"], f"EventhouseQueryLogs | where Timestamp > {t} and DatabaseName == 'obs_fleet' "
                              f"and QueryText has 'battery overheat' | summarize runs=count(), firstTs=min(Timestamp), "
                              f"lastTs=max(Timestamp), avg_ms=avg(DurationMs), cpu_ms=sum(totimespan(CpuTimeMs)/1ms)")
    notes = kql(qu, db["id"], f"ActivatorRuleNotifications | where Timestamp > {t} | summarize n=count(), "
                              f"ts=make_list(Timestamp) by ItemName, Status")
    print("\nAgent rule queries (opa_obs_portal):", json.dumps(agent, indent=1))
    print("\nActivator notifications:", json.dumps(notes, indent=1))


def main() -> None:
    import sys
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    p = argparse.ArgumentParser()
    p.add_argument("action", choices=["create", "start", "stop", "status", "evidence"])
    p.add_argument("--phase", type=int, default=1)
    p.add_argument("--name", default=FLEET)
    p.add_argument("--since", help="evidence: ISO start of the trial (UTC)")
    p.add_argument("--truth", default="../data-gen/out_obs_p1", help="evidence: generator --out folder")
    a = p.parse_args()
    load_env()
    if a.action == "evidence":
        evidence(a.since, a.truth)
    elif a.action == "create":
        create(a.phase)
    elif a.action in ("start", "stop"):
        set_run(a.name, a.action == "start")
    else:
        status()


if __name__ == "__main__":
    main()
