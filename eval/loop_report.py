"""Step 11 live2.5: Git-tracked loop report (eval/reports/live2.5.md) from eval/runs/loop_state.json and the local runs."""
from __future__ import annotations

from collections import Counter, defaultdict

import agent_eval as ae
import graders

ARCHITECTURE = """```mermaid
flowchart LR
  G["Golden set (Git)<br/>train / validation / test"] --> C["1 Collect<br/>head + candidate, same run"]
  C --> H["Arm head agent (lab_)"] & K["Candidate lab_&lt;arm&gt;_cN"]
  H & K --> SRC["Ontology + source data<br/>ont_contoso, lh_asset hub, lh_finance, eh_fleet"]
  C --> S["2 Grade: rules + Decision-1"]
  S --> EH[("3 Eventhouse lab_agent_eval<br/>answers, steps (source per tool call), scores,<br/>agent_versions, improvements, loop_events")]
  EH --> DASH["Real-Time dashboard + Activator"]
  EH --> D["4 Diagnose: train failures + generated query"]
  D --> O["5 Optimizer gpt-4.1 (Foundry)"] --> GR["6 Guardrails: leakage, PII rule,<br/>size, few-shots execute"]
  GR --> B["7 Publish candidate"] --> K
  S --> A{"8 Accept on validation?"}
  A -- yes --> H
  A -- no --> X["Delete candidate"]
  A --> EH
```"""


def _f(t) -> str:
    return f"{t[0]}/{t[1]}" if t and t[1] else "-"


def _pct(t) -> str:
    return f"{100 * t[0] / t[1]:.0f}%" if t and t[1] else "-"


def write(state: dict) -> None:
    loop_id = state["loop_id"]
    lines = [f"# Data agent feedback loop: {loop_id}", "",
             "Sample, not production guidance. Synthetic data. Generated by `py eval/feedback_loop.py report`. "
             f"Capacity: {state.get('sku') or '?'}. The live timeline, sources and tokens are in the `lab_rtd_agent_eval` "
             "Real-Time dashboard (Eventhouse `lab_agent_eval`).", "", "## Architecture", "", ARCHITECTURE, "",
             "Splits: proposals come only from **train** failures, candidates are accepted on **validation** "
             "(train gain ≥ 2 questions, validation not worse, no forbidden-data failure, no category drop > 1), "
             "and **test** is scored once, at the end. Heads and candidates are asked in the same run (paired).", "",
             "## Result", "", "| Arm | v0 | Final head | Test v0 → head | All questions v0 → head | Rounds accepted |",
             "|---|---|---|---|---|---|"]
    for a, st in state["arms"].items():
        f = st.get("final") or {}
        allq = lambda s: (sum(s[k][0] for k in ("train", "validation", "test")),  # noqa: E731
                          sum(s[k][1] for k in ("train", "validation", "test"))) if s else None
        acc = sum(1 for h in st["history"] if h.get("accepted"))
        lines.append(f"| {a} | `{st['v0']}` | `{st['head']}` | {_pct(f.get('v0', {}).get('test'))} → "
                     f"{_pct(f.get('head', {}).get('test'))} | {_pct(allq(f.get('v0')))} → {_pct(allq(f.get('head')))} | "
                     f"{acc} |")
    for a, st in state["arms"].items():
        lines += ["", f"## Arm {a}: rounds", "", "| Round | Head | Candidate | Train head → cand | "
                  "Validation head → cand | Decision | Reason | Optimizer tokens |", "|---|---|---|---|---|---|---|---|"]
        for h in st["history"]:
            if h["round"] == 0:
                s = h["stats"]
                lines.append(f"| 0 (baseline) | `{h['head']}` | - | {_f(s['train'])} | {_f(s['validation'])} | - | - | - |")
                continue
            tok = h.get("optimizer_tokens") or [0, 0]
            lines.append(f"| {h['round']} | `{h['head']}` | `{h.get('candidate', '-')}` | {_f(h['base']['train'])} → "
                         f"{_f(h['cand']['train'])} | {_f(h['base']['validation'])} → {_f(h['cand']['validation'])} | "
                         f"{'accepted' if h['accepted'] else 'rejected'} | {h['reason']} | {tok[0]:,}/{tok[1]:,} |")
        accepted = [h for h in st["history"] if h.get("accepted")]
        if accepted:
            lines += ["", f"### Arm {a}: accepted changes", ""]
            for h in accepted:
                p = h["proposal"]
                lines.append(f"Round {h['round']} (`{h['candidate']}`):")
                lines += [f"- Instruction: {x}" for x in p["instructions_add"]]
                lines += [f"- `{k}` instruction: {x}" for k, v in p["datasource_instructions_add"].items() for x in v]
                lines += [f"- Few-shot ({x['datasource']}): {x['question']}" for x in p["fewshots"]]
                lines.append("")
    if state.get("final_run"):
        recs = ae.read_jsonl(ae.run_dir(state["final_run"]) / "responses.jsonl")
        lines += ["", "## Sources and tokens (final run)", "",
                  "Share of executed queries per data source (from the agent's run steps) and token usage per answer.", "",
                  "| Agent | Queries by source | Answers without a query | Prompt tokens / answer | Completion tokens / answer | p50 latency |",
                  "|---|---|---|---|---|---|"]
        by_agent = defaultdict(list)
        for r in recs:
            by_agent[r["agent"]].append(r)
        for ag, rs in sorted(by_agent.items()):
            srcs = Counter(c["datasource"] for r in rs for c in r.get("tool_calls", [])
                           if c.get("tool") == "analyze.database.execute" and c.get("datasource"))
            total = sum(srcs.values()) or 1
            mix = ", ".join(f"{k} {100 * v / total:.0f}%" for k, v in srcs.most_common())
            none = sum(1 for r in rs if not any(c.get("tool") == "analyze.database.execute" for c in r.get("tool_calls", [])))
            n = len(rs)
            lines.append(f"| `{ag}` | {mix or '-'} | {none}/{n} | {sum(r.get('prompt_tokens') or 0 for r in rs) // n:,} | "
                         f"{sum(r.get('completion_tokens') or 0 for r in rs) // n:,} | "
                         f"{graders.percentile([r.get('latency_s') for r in rs], 0.5)} s |")
    ae.REPORTS.mkdir(parents=True, exist_ok=True)
    path = ae.REPORTS / "live2.5.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(path)
